"""迁移与 ORM 同步性测试（CI 守门用例）。

要解决的问题：改了 ORM 模型却忘记生成迁移，代码在开发库上「碰巧能跑」，
上线时才在 `alembic upgrade` 阶段炸掉——这是最难在联调期发现的一类事故。

做法分两步，缺一不可：
1. **可执行性**：在空库上 `upgrade head` 必须成功。迁移自身写错（缺 import、
   顺序违反外键依赖、方言不兼容）会在这一步暴露。
2. **一致性**：升级完成后执行 `alembic check`，它会用 Autogenerate 比对
   「迁移建出来的库」与「当前的 ORM 元数据」，有任何差异就抛错。
   这一步能抓住「模型加了列、但没写迁移」这种漂移。

为什么用 SQLite：CI 里不必为了这一条用例拉起 PostgreSQL；DDL 正确性与
「模型-迁移是否一致」这两个属性与具体方言无关。PostgreSQL 专属的 RLS 策略
由迁移内部按方言判断跳过，不影响本用例结论。
"""

from __future__ import annotations

import os
from pathlib import Path

import pytest
from alembic.config import Config

from alembic import command
from app.core.config import get_settings

BACKEND_DIR = Path(__file__).resolve().parent.parent
# 不用 pytest 的 tmp_path：在部分 Windows 环境下系统临时目录不可写
# （WinError 5），而这里只需要一个「用完即删」的库文件，放在项目内更可靠。
# 该目录已加入 .gitignore，不会污染工作区。
_WORK_DIR = BACKEND_DIR / "_mig_check"


def _alembic_config(db_path: Path) -> Config:
    """构造指向临时库的 Alembic 配置。

    注意 `alembic.ini` 的 `sqlalchemy.url` 留空是刻意设计——真实 DSN 由
    `alembic/env.py` 从应用配置读取。因此这里除了改 ini，还要通过环境变量
    覆盖 `DATABASE_URL`，否则会连到开发库上（那是最危险的情况：
    测试会去改真实数据库）。
    """
    cfg = Config(str(BACKEND_DIR / "alembic.ini"))
    cfg.set_main_option("script_location", str(BACKEND_DIR / "alembic"))
    cfg.set_main_option("sqlalchemy.url", f"sqlite+aiosqlite:///{db_path.as_posix()}")
    return cfg


@pytest.fixture
def isolated_db(monkeypatch):
    """把 DATABASE_URL 指向临时文件库，用例结束后删除文件并还原配置缓存。"""
    _WORK_DIR.mkdir(exist_ok=True)
    db_path = _WORK_DIR / f"drift_{os.getpid()}.db"
    if db_path.exists():
        db_path.unlink()

    monkeypatch.setenv("DATABASE_URL", f"sqlite+aiosqlite:///{db_path.as_posix()}")
    # Settings 是 lru_cache 的，改环境变量后必须清缓存才会重新读取
    get_settings.cache_clear()
    try:
        yield db_path
    finally:
        get_settings.cache_clear()
        # 释放 SQLite 文件句柄后再删，避免 Windows 上的「文件被占用」
        for candidate in (db_path, db_path.with_suffix(".db-wal"), db_path.with_suffix(".db-shm")):
            if candidate.exists():
                try:
                    candidate.unlink()
                except OSError:
                    pass


def test_initial_migration_applies_on_empty_database(isolated_db):
    """空库能一路升级到 head，且建出的表覆盖全部 ORM 表。"""
    cfg = _alembic_config(isolated_db)
    command.upgrade(cfg, "head")

    # 迁移执行后，库里应有业务表 + alembic_version
    import sqlite3

    conn = sqlite3.connect(isolated_db)
    try:
        actual = {
            row[0]
            for row in conn.execute("select name from sqlite_master where type='table'")
            if not row[0].startswith("sqlite_")
        }
    finally:
        conn.close()

    from app.models import Base

    expected = set(Base.metadata.tables) | {"alembic_version"}
    missing = expected - actual
    assert not missing, f"迁移未创建下列 ORM 表: {sorted(missing)}"


def test_models_and_migrations_have_no_drift(isolated_db):
    """模型与迁移零差异——新增字段必须先写迁移才能进主干。"""
    cfg = _alembic_config(isolated_db)
    command.upgrade(cfg, "head")

    # command.check 内部走 Autogenerate 比对；有差异时抛 AutogenerateDiffsDetected，
    # 异常消息会列出「新增/删除/修改」的表与列，便于直接定位漏掉的迁移。
    command.check(cfg)
